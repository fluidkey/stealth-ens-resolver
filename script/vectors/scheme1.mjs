// Generates test/utils/Scheme1Vectors.sol: ERC-5564 scheme 1 derivations computed by the ScopeLift
// stealth-address SDK, one per parity combination of the spending key, the viewing key and the
// shared secret point. Every vector is also rederived here from the curve operations, so the
// SDK and this repo's reading of scheme 1 (keccak256 of the compressed shared secret point) agree.
//
//   npm install --prefix <dir> --ignore-scripts @scopelift/stealth-address-sdk@1.0.0-beta.5
//   node script/vectors/scheme1.mjs <dir> > test/utils/Scheme1Vectors.sol && forge fmt
//
// Deterministic: keys are hashes of fixed labels, so the output only changes with the SDK.

import { readFileSync } from "node:fs";
import { register } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// The SDK's build uses bundler-style relative imports ('./types', './foo'): resolve them as
// Node would for CommonJS, `.js` then `/index.js`.
register(
  `data:text/javascript,${encodeURIComponent(`export async function resolve(s, c, next) {
    try { return await next(s, c); } catch (e) {
      if (!s.startsWith(".")) throw e;
      try { return await next(s + ".js", c); } catch { return next(s + "/index.js", c); }
    }
  }`)}`,
);

const dir = process.argv[2];
if (!dir) throw new Error("usage: node script/vectors/scheme1.mjs <dir with the SDK installed>");
const load = (p) => import(pathToFileURL(join(dir, "node_modules", p)).href);
const version = (p) =>
  JSON.parse(readFileSync(join(dir, "node_modules", p, "package.json"))).version;

const sdk = await load("@scopelift/stealth-address-sdk/dist/utils/crypto/generateStealthAddress.js");
const { VALID_SCHEME_ID } = await load("@scopelift/stealth-address-sdk/dist/utils/crypto/types/index.js");
const secp = await load("@noble/secp256k1/index.js");
const { keccak256, toHex, bytesToHex, getAddress, publicKeyToAddress } = await load(
  "viem/_esm/utils/index.js",
);

const n = secp.CURVE.n;
const assert = (ok, msg) => {
  if (!ok) throw new Error(msg);
};
const key = (label, i) => {
  const k = (BigInt(keccak256(toHex(`scheme1-vector-${label}-${i}`))) % (n - 1n)) + 1n;
  return secp.etc.hexToBytes(k.toString(16).padStart(64, "0"));
};
const hex = (b) => bytesToHex(b).slice(2);

const vectors = new Array(8);
for (let i = 0, found = 0; found < 8; ++i) {
  const spend = secp.getPublicKey(key("spend", i), true);
  const view = secp.getPublicKey(key("view", i), true);
  const eph = key("ephemeral", i);
  const shared = secp.getSharedSecret(eph, view, false); // 0x04 || x || y
  const slot = (spend[0] - 2) * 4 + (view[0] - 2) * 2 + (shared[64] & 1);
  if (vectors[slot]) continue;

  const meta = `${hex(spend)}${hex(view)}`;
  const r = sdk.generateStealthAddress({
    stealthMetaAddressURI: `st:eth:0x${meta}`,
    schemeId: VALID_SCHEME_ID.SCHEME_ID_1,
    ephemeralPrivateKey: eph,
  });
  // The SDK silently substitutes a random key for one it rejects.
  assert(r.ephemeralPublicKey === bytesToHex(secp.getPublicKey(eph, true)), "ephemeral key replaced");

  // Rederived from the curve: s_h = keccak256(compressed S), P = P_spend + s_h·G.
  const sh = keccak256(secp.getSharedSecret(eph, view, true));
  assert(r.viewTag === sh.slice(0, 4), "view tag differs: the SDK does not hash the compressed point");
  const stealth = secp.Point.fromBytes(spend).add(secp.Point.BASE.multiply(BigInt(sh) % n));
  const derived = publicKeyToAddress(bytesToHex(stealth.toBytes(false)));
  assert(getAddress(derived) === getAddress(r.stealthAddress), "stealth address differs");

  vectors[slot] = { meta, vd: `${hex(eph)}${hex(shared.slice(1))}`, address: getAddress(r.stealthAddress) };
  ++found;
}

const sdkVersion = version("@scopelift/stealth-address-sdk");
const nobleVersion = version("@noble/secp256k1");
process.stdout.write(`// SPDX-License-Identifier: MIT
pragma solidity 0.8.25;

// Generated by script/vectors/scheme1.mjs from @scopelift/stealth-address-sdk@${sdkVersion}
// (@noble/secp256k1@${nobleVersion}). Do not edit: regenerate, then \`forge fmt\`.

/// @dev ERC-5564 scheme 1 derivations by the ScopeLift SDK. Vector i has spending key parity
///      i >> 2, viewing key parity (i >> 1) & 1 and shared secret point parity i & 1.
library Scheme1Vectors {
    struct Vector {
        /// @dev Compressed spending key || compressed viewing key (66 bytes).
        bytes metaAddress;
        /// @dev Ephemeral private key || shared secret point x || y (96 bytes).
        bytes verificationData;
        /// @dev The SDK's stealth address.
        address stealthAddress;
    }

    function all() internal pure returns (Vector[] memory v) {
        v = new Vector[](8);
${vectors.map((x, i) => `        v[${i}] = Vector(hex"${x.meta}", hex"${x.vd}", ${x.address});`).join("\n")}
    }
}
`);
